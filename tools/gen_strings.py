def esc(s):
    s = s.replace("&amp;","&")
    return escape(s).replace("'", "\\'").replace('"','\\"')
root = sys.argv[1]
for i,folder in enumerate(["values","values-ar","values-iw"]):
    os.makedirs(f"{root}/{folder}", exist_ok=True)
    with open(f"{root}/{folder}/strings.xml","w",encoding="utf-8") as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n<resources>\n')
        for k,v in S.items():
            attr = ' translatable="false"' if k=="app_name" and i==0 else ''
            if k=="app_name" and i>0: continue
            f.write(f'    <string name="{k}"{attr}>{esc(v[i])}</string>\n')
        f.write('</resources>\n')
print(len(S), "strings")
